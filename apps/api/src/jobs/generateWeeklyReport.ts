function hasErrorCode(error: unknown, code: string): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    "code" in error &&
    error.code === code
  );
}

async function removeTemporaryFile(filePath: string): Promise<void> {
  try {
    await unlink(filePath);
  } catch (error) {
    if (!hasErrorCode(error, "ENOENT")) {
      throw error;
    }
  }
}

async function writeReportAtomically(
  reportDirectory: string,
  reportDate: string,
  content: string,
): Promise<string> {
  await mkdir(reportDirectory, { recursive: true, mode: 0o700 });

  for (let revision = 1; ; revision += 1) {
    const revisionSuffix =
      revision === 1 ? "" : `-r${String(revision).padStart(2, "0")}`;
    const filename = `weekly-status-report-${reportDate}${revisionSuffix}.md`;
    const reportPath = path.join(reportDirectory, filename);
    const temporaryPath = path.join(
      reportDirectory,
      `.${filename}.${randomUUID()}.tmp`,
    );

    try {
      await writeFile(temporaryPath, content, {
        encoding: "utf8",
        flag: "wx",
        mode: 0o600,
      });
    } catch (error) {
      await removeTemporaryFile(temporaryPath);
      throw error;
    }

    try {
      await link(temporaryPath, reportPath);
    } catch (error) {
      await removeTemporaryFile(temporaryPath);
      if (hasErrorCode(error, "EEXIST")) {
        continue;
      }
      throw error;
    }

    await unlink(temporaryPath);
    return reportPath;
  }
}

export async function generateWeeklyReport(
  options: GenerateWeeklyReportOptions = {},
): Promise<GeneratedReport> {
  const generatedAt = options.generatedAt ?? new Date();
  if (!(generatedAt instanceof Date) || Number.isNaN(generatedAt.getTime())) {
    throw new TypeError("generatedAt must be a valid date.");
  }

  const periodStart = new Date(
    generatedAt.getTime() - 7 * DAY_IN_MILLISECONDS,
  );
  const content = renderMockReport(generatedAt, periodStart);
  const canonicalPath = await writeReportAtomically(
    options.reportDirectory ?? REPORT_DIRECTORY,
    getLocalDate(generatedAt),
    content,
  );

  return {
    id: randomUUID(),
    generatedAt: generatedAt.toISOString(),
    reportingPeriodStart: periodStart.toISOString(),
    reportingPeriodEnd: generatedAt.toISOString(),
    canonicalPath,
    content,
  };
}
